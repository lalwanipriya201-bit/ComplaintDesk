
using ComplaintMgtSystem.Data;
using ComplaintMgtSystem.Models;
using Microsoft.AspNetCore.Authorization;
using Microsoft.AspNetCore.Mvc;
using Microsoft.AspNetCore.Mvc.Rendering;
using Microsoft.EntityFrameworkCore;
using System.Security.Claims;

namespace ComplaintMgtSystem.Controllers
{
    [Authorize]
    public class ComplaintController : Controller
    {
        private readonly ApplicationDbContext _context;

        public ComplaintController(ApplicationDbContext context)
        {
            _context = context;
        }

        // GET: /Complaint/Create
        [Authorize(Roles = "User")]
        [HttpGet]
        public async Task<IActionResult> Create()
        {
            await LoadCategories();
            return View();
        }

        // POST: /Complaint/Create
        [Authorize(Roles = "User")]
        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> Create(Complaint model)
        {
            // These values must be generated by the server.
            ModelState.Remove(nameof(model.ComplaintNumber));
            ModelState.Remove(nameof(model.UserId));
            ModelState.Remove(nameof(model.Status));
            ModelState.Remove(nameof(model.CreatedAt));
            ModelState.Remove(nameof(model.UpdatedAt));
            ModelState.Remove(nameof(model.ResolvedAt));
            ModelState.Remove(nameof(model.AdminRemark));

            if (!ModelState.IsValid)
            {
                await LoadCategories(model.CategoryId);
                return View(model);
            }

            int userId = int.Parse(
                User.FindFirstValue(ClaimTypes.NameIdentifier)!);

            bool categoryExists = await _context.Categories
                .AnyAsync(c => c.Id == model.CategoryId);

            if (!categoryExists)
            {
                ModelState.AddModelError(
                    nameof(model.CategoryId),
                    "Please select a valid category.");

                await LoadCategories(model.CategoryId);
                return View(model);
            }

            // Generate a sequential complaint number.
            // The database Id is the unique identifier.
            var complaint = new Complaint
            {
                ComplaintNumber = "TEMP",
                UserId = userId,
                CategoryId = model.CategoryId,
                Subject = model.Subject.Trim(),
                Description = model.Description.Trim(),
                Priority = model.Priority,
                Status = "Pending",
                CreatedAt = DateTime.UtcNow,
                UpdatedAt = DateTime.UtcNow
            };

            if (complaint.Priority != "Low" &&
                complaint.Priority != "Medium" &&
                complaint.Priority != "High")
            {
                ModelState.AddModelError(
                    nameof(model.Priority),
                    "Please select a valid priority.");

                await LoadCategories(model.CategoryId);
                return View(model);
            }

            _context.Complaints.Add(complaint);
            await _context.SaveChangesAsync();

            complaint.ComplaintNumber =
                $"CMP-{DateTime.UtcNow.Year}-{complaint.Id:D4}";

            await _context.SaveChangesAsync();

            _context.ComplaintStatusHistories.Add(
                new ComplaintStatusHistory
                {
                    ComplaintId = complaint.Id,
                    OldStatus = "Submitted",
                    NewStatus = "Pending",
                    ChangedBy = userId,
                    ChangedAt = DateTime.UtcNow,
                    Remark = "Complaint submitted."
                });

            await _context.SaveChangesAsync();

            TempData["SuccessMessage"] =
                $"Complaint {complaint.ComplaintNumber} submitted successfully.";

            return RedirectToAction(nameof(MyComplaints));
        }

        // GET: /Complaint/MyComplaints
        [Authorize(Roles = "User")]
        [HttpGet]
        public async Task<IActionResult> MyComplaints()
        {
            int userId = int.Parse(
                User.FindFirstValue(ClaimTypes.NameIdentifier)!);

            var complaints = await _context.Complaints
                .Include(c => c.Category)
                .Where(c => c.UserId == userId)
                .OrderByDescending(c => c.CreatedAt)
                .ToListAsync();

            return View(complaints);
        }
        // GET: /Complaint/Details/5
        [Authorize(Roles = "User")]
        [HttpGet]
        public async Task<IActionResult> Details(int id)
        {
            int userId = int.Parse(
                User.FindFirstValue(ClaimTypes.NameIdentifier)!);

            var complaint = await _context.Complaints
                .Include(c => c.Category)
                .Include(c => c.Comments)
                    .ThenInclude(c => c.User)
                .Include(c => c.StatusHistory)
                    .ThenInclude(h => h.ChangedByUser)
                .FirstOrDefaultAsync(c =>
                    c.Id == id && c.UserId == userId);

            if (complaint == null)
            {
                return NotFound();
            }

            return View(complaint);
        }
                
        // GET: /Complaint/AllComplaints
        [Authorize(Roles = "Admin")]
        [HttpGet]
        public async Task<IActionResult> AllComplaints(
            string? search,
            string? status,
            int? categoryId,
            string? priority,
            DateTime? fromDate,
            DateTime? toDate)
        {
            var query = _context.Complaints
                .Include(c => c.Category)
                .Include(c => c.User)
                .AsQueryable();

            if (!string.IsNullOrWhiteSpace(search))
            {
                search = search.Trim();

                query = query.Where(c =>
                    c.ComplaintNumber.Contains(search) ||
                    c.Subject.Contains(search));
            }

            if (!string.IsNullOrWhiteSpace(status))
            {
                query = query.Where(c => c.Status == status);
            }

            if (categoryId.HasValue)
            {
                query = query.Where(c => c.CategoryId == categoryId.Value);
            }

            if (!string.IsNullOrWhiteSpace(priority))
            {
                query = query.Where(c => c.Priority == priority);
            }

            if (fromDate.HasValue)
            {
                var startDate = fromDate.Value.Date;
                query = query.Where(c => c.CreatedAt >= startDate);
            }

            if (toDate.HasValue)
            {
                var endDateExclusive = toDate.Value.Date.AddDays(1);
                query = query.Where(c => c.CreatedAt < endDateExclusive);
            }

            ViewBag.Search = search;
            ViewBag.Status = status;
            ViewBag.CategoryId = categoryId;
            ViewBag.Priority = priority;
            ViewBag.FromDate = fromDate?.ToString("yyyy-MM-dd");
            ViewBag.ToDate = toDate?.ToString("yyyy-MM-dd");

            ViewBag.Categories = new SelectList(
                await _context.Categories.OrderBy(c => c.Name).ToListAsync(),
                "Id",
                "Name",
                categoryId);

            return View(await query
                .OrderByDescending(c => c.CreatedAt)
                .ToListAsync());
        }
        

        // GET: /Complaint/AdminDetails/5
        [Authorize(Roles = "Admin")]
        [HttpGet]
        public async Task<IActionResult> AdminDetails(int id)
        {
            var complaint = await _context.Complaints
                .Include(c => c.Category)
                .Include(c => c.User)
                .Include(c => c.Comments)
                    .ThenInclude(c => c.User)
                .Include(c => c.StatusHistory)
                    .ThenInclude(h => h.ChangedByUser)
                .FirstOrDefaultAsync(c => c.Id == id);

            if (complaint == null)
            {
                return NotFound();
            }

            return View(complaint);
        }
        
        // POST: /Complaint/UpdateStatus
        [Authorize(Roles = "Admin")]
        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> UpdateStatus(
            int id,
            string status,
            string? adminRemark)
        {
            var allowedStatuses = new[]
            {
                "Pending",
                "In Progress",
                "Resolved",
                "Closed",
                "Rejected"
            };

            if (string.IsNullOrWhiteSpace(status) ||
                !allowedStatuses.Contains(status))
            {
                return BadRequest("Invalid complaint status.");
            }

            var complaint = await _context.Complaints
                .FirstOrDefaultAsync(c => c.Id == id);

            if (complaint == null)
            {
                return NotFound();
            }

            int adminId = int.Parse(
                User.FindFirstValue(ClaimTypes.NameIdentifier)!);

            string oldStatus = complaint.Status;
            bool statusChanged = oldStatus != status;

            complaint.Status = status;
            complaint.AdminRemark = string.IsNullOrWhiteSpace(adminRemark)
                ? null
                : adminRemark.Trim();

            complaint.UpdatedAt = DateTime.UtcNow;

            if (status == "Resolved")
            {
                complaint.ResolvedAt ??= DateTime.UtcNow;
            }
            else
            {
                complaint.ResolvedAt = null;
            }

            if (statusChanged)
            {
                _context.ComplaintStatusHistories.Add(
                    new ComplaintStatusHistory
                    {
                        ComplaintId = complaint.Id,
                        OldStatus = oldStatus,
                        NewStatus = status,
                        ChangedBy = adminId,
                        ChangedAt = DateTime.UtcNow,
                        Remark = complaint.AdminRemark
                    });
            }

            await _context.SaveChangesAsync();

            TempData["SuccessMessage"] =
                $"Complaint {complaint.ComplaintNumber} updated successfully.";

            return RedirectToAction(
                nameof(AdminDetails),
                new { id = complaint.Id });
        }

        
        // POST: /Complaint/AddComment
        [Authorize(Roles = "User,Admin")]
        [HttpPost]
        [ValidateAntiForgeryToken]
        public async Task<IActionResult> AddComment(int complaintId, string comment)
        {
            if (string.IsNullOrWhiteSpace(comment))
            {
                TempData["ErrorMessage"] = "Comment cannot be empty.";
                return RedirectToAction(
                    User.IsInRole("Admin") ? nameof(AdminDetails) : nameof(Details),
                    new { id = complaintId });
            }

            if (comment.Trim().Length > 1000)
            {
                TempData["ErrorMessage"] = "Comment cannot exceed 1000 characters.";
                return RedirectToAction(
                    User.IsInRole("Admin") ? nameof(AdminDetails) : nameof(Details),
                    new { id = complaintId });
            }

            int userId = int.Parse(
                User.FindFirstValue(ClaimTypes.NameIdentifier)!);

            var complaint = await _context.Complaints
                .FirstOrDefaultAsync(c => c.Id == complaintId);

            if (complaint == null)
            {
                return NotFound();
            }

            // Users may comment only on their own complaints.
            if (User.IsInRole("User") && complaint.UserId != userId)
            {
                return Forbid();
            }

            var newComment = new ComplaintComment
            {
                ComplaintId = complaintId,
                UserId = userId,
                Comment = comment.Trim(),
                CreatedAt = DateTime.UtcNow
            };

            _context.ComplaintComments.Add(newComment);
            await _context.SaveChangesAsync();

            TempData["SuccessMessage"] = "Comment added successfully.";

            return RedirectToAction(
                User.IsInRole("Admin") ? nameof(AdminDetails) : nameof(Details),
                new { id = complaintId });
        }
    
        

        private async Task LoadCategories(int? selectedId = null)
        {
            ViewBag.Categories = new SelectList(
                await _context.Categories
                    .OrderBy(c => c.Name)
                    .ToListAsync(),
                "Id",
                "Name",
                selectedId);
        }
    }
}
